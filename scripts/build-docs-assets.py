#!/usr/bin/env python3
"""Generate docs assets FROM the language repo (read-only), so they never drift:

  1. docs/.vitepress/tantu.tmLanguage.json  = Shiki grammar, from tantu/tokens.py's keyword set
  2. docs/reference/_errors.generated.md   = every code in tantu/errors.py + curated descriptions
  3. docs/reference/_builtins.generated.md = Appendix A builtins, validated against BUILTIN_SIGS
  4. docs/public/llms.txt + llms-full.txt   = the guide for LLMs (llmstxt.org): an index + every page in one file

The error table's CODE LIST is authoritative (pulled live from errors.py); a code missing a
curated description in reference/error-descriptions.json is a hard error, so a newly added
language code forces a docs update instead of silently going missing.
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WEB = HERE.parent
LANG_REPO = Path(os.environ.get("TANTU_LANG_REPO", WEB / ".." / "Combined Interpreter")).resolve()
DOCS = WEB / "docs"

# Import the real language modules (pure-Python, stdlib-only): from the language repo when it's
# checked out next to us, otherwise from the vendored wheel in playground/public/ (a pure-Python
# wheel is a zip, so putting it on sys.path makes its packages importable). The wheel fallback is
# what lets CI (e.g. Netlify) build the docs without the language repo.
if LANG_REPO.exists():
    sys.path.insert(0, str(LANG_REPO))
else:
    _public = WEB / "playground" / "public"
    _manifest = _public / "tantu-wheel.json"
    if not _manifest.exists():
        sys.stderr.write(
            f"[build-docs-assets] ERROR: language repo not found at {LANG_REPO} "
            f"and no vendored wheel manifest at {_manifest}\n"
        )
        sys.exit(1)
    _wheel = _public / json.loads(_manifest.read_text())["wheel"]
    print(f"[build-docs-assets] language repo not found; importing from vendored {_wheel.name}")
    sys.path.insert(0, str(_wheel))

import tantu.errors as werrors          # noqa: E402
from tantu.prelude import BUILTIN_SIGS  # noqa: E402
from tantu.tokens import KEYWORDS       # noqa: E402

# Type names + call-position builtins: the same token set the CodeMirror editor uses.
TYPE_NAMES = ["Int", "Float", "Bool", "Str", "Unit", "List", "Tuple", "Chan", "Option", "Result"]
BUILTIN_NAMES = [
    "print", "len", "push", "get", "concat", "range", "float", "trunc", "parse_int",
    "split", "substring", "chars", "str", "chan", "send", "recv", "close", "sleep",
]

STAGE = {"L": "lex", "P": "parse", "E": "check", "R": "runtime"}


def _fail(msg: str) -> None:
    sys.stderr.write(f"[build-docs-assets] ERROR: {msg}\n")
    sys.exit(1)


# --------------------------------------------------------------------- 1. Shiki grammar
def gen_grammar() -> dict:
    keywords = sorted(KEYWORDS.keys())
    return {
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        "name": "tantu",
        "scopeName": "source.tn",
        "patterns": [
            {"name": "comment.line.number-sign.tn", "match": "#.*$"},
            {"name": "string.quoted.double.tn", "begin": "\"", "end": "\"",
             "patterns": [{"name": "constant.character.escape.tn", "match": "\\\\."}]},
            {"name": "constant.numeric.tn", "match": r"\b[0-9][0-9_]*(\.[0-9_]+)?\b"},
            {"name": "keyword.control.tn", "match": r"\b(" + "|".join(keywords) + r")\b"},
            {"name": "support.type.tn", "match": r"\b(" + "|".join(TYPE_NAMES) + r")\b"},
            {"name": "support.function.tn", "match": r"\b(" + "|".join(BUILTIN_NAMES) + r")\b"},
            {"name": "entity.name.type.tn", "match": r"\b[A-Z][A-Za-z0-9_]*\b"},
            {"name": "keyword.operator.tn",
             "match": r"(->|=>|==|!=|<=|>=|[:=<>+\-*/%?.,])"},
        ],
    }


# --------------------------------------------------------------------- 2. error-code table
def gen_errors() -> str:
    codes = {v: k for k, v in vars(werrors).items()
             if isinstance(v, str) and re.fullmatch(r"[LPER]\d{3,4}", v)}
    descriptions = json.loads((DOCS / "reference" / "error-descriptions.json").read_text())

    missing = [c for c in codes if c not in descriptions]
    if missing:
        _fail("no curated description for error code(s): " + ", ".join(sorted(missing))
              + "\n  add them to docs/reference/error-descriptions.json")

    def kebab(const_name: str) -> str:
        # E_VAR_CAPTURE -> var-capture ; L_TABS_IN_INDENT -> tabs-in-indent
        return const_name.split("_", 1)[1].lower().replace("_", "-")

    rows = ["| Code | Name | Stage | Meaning |", "|------|------|-------|---------|"]
    for code in sorted(codes):
        rows.append(f"| `{code}` | {kebab(codes[code])} | {STAGE[code[0]]} | {descriptions[code]} |")
    return ("<!-- GENERATED by scripts/build-docs-assets.py from tantu/errors.py; do not edit. -->\n\n"
            + "\n".join(rows) + "\n")


# --------------------------------------------------------------------- 3. builtins table
# Appendix A (the complete v1 list, incl. opcode-backed intrinsics not in BUILTIN_SIGS).
APPENDIX_A = [
    ("print", "(T) -> Unit", "any value; prints via the PRINT op"),
    ("str", "(T) -> Str", "render to a string (a Str is returned unquoted)"),
    ("len", "(List[T]) -> Int, (Str) -> Int", "length; two overloads"),
    ("push", "(List[T], T) -> List[T]", "returns a NEW list (lists are immutable by convention)"),
    ("get", "(List[T], Int) -> Option[T]", "safe index; None when out of range"),
    ("concat", "(List[T], List[T]) -> List[T]", "join two lists"),
    ("range", "(Int, Int) -> List[Int]", "half-open [a, b)"),
    ("float", "(Int) -> Float", "widen an Int"),
    ("trunc", "(Float) -> Int", "truncate toward zero"),
    ("parse_int", "(Str) -> Option[Int]", "None if not an integer"),
    ("split", "(Str, Str) -> List[Str]", "split on a separator"),
    ("substring", "(Str, Int, Int) -> Str", "half-open, clamps to bounds"),
    ("chars", "(Str) -> List[Str]", "explode into single-character strings"),
    ("chan[T](n?)", "() -> Chan[T] / (Int) -> Chan[T]", "make a channel (optional buffer size)"),
    ("send", "(Chan[T], T) -> Unit", "send a value (blocks when full)"),
    ("recv", "(Chan[T]) -> Option[T]", "receive; None when the channel is closed + drained"),
    ("close", "(Chan[T]) -> Unit", "close a channel"),
    ("sleep", "(Int) -> Unit", "yield for N milliseconds"),
]


def gen_builtins() -> str:
    listed = {row[0].split("[")[0].split("(")[0] for row in APPENDIX_A}
    unlisted = [name for name in BUILTIN_SIGS if name not in listed]
    if unlisted:
        _fail("BUILTIN_SIGS has names missing from the docs builtins table: " + ", ".join(unlisted))

    rows = ["| Name | Signature | Notes |", "|------|-----------|-------|"]
    for name, sig, note in APPENDIX_A:
        rows.append(f"| `{name}` | `{sig}` | {note} |")
    return ("<!-- GENERATED by scripts/build-docs-assets.py; do not edit. -->\n\n"
            + "\n".join(rows) + "\n")


# --------------------------------------------------------------------- 4. llms.txt
SITE = "https://tantu-play.netlify.app"
# Sidebar order from docs/.vitepress/config.ts; keep the two lists in step.
LLM_PAGES = [
    ("Introduction", "index"), ("Quick start", "guide/quick-start"), ("Language tour", "guide/tour"),
    ("Syntax", "guide/syntax"), ("Types & no-null", "guide/types"),
    ("Pattern matching", "guide/pattern-matching"), ("Functions & closures", "guide/functions"),
    ("Concurrency", "guide/concurrency"), ("Modules", "guide/modules"), ("Generics", "guide/generics"),
    ("Under the hood", "guide/under-the-hood"), ("Builtins", "reference/builtins"),
    ("Error codes", "reference/errors"),
]
LLM_SUMMARY = ("> Tantu is a statically-typed, Python-readable language with no null, pattern matching, "
               "generics, and fibers that talk over typed channels. It runs on a bytecode VM written in Python "
               "(`pip install tantu`, then `tantu run file.tn`).")


def gen_llms() -> tuple[str, str]:
    index = ["# Tantu", "", LLM_SUMMARY, "", "## Docs", ""]
    index += [f"- [{title}]({SITE}/{path.removesuffix('index')})" for title, path in LLM_PAGES]
    index += ["", "## Optional", "", f"- [Every page above in one file]({SITE}/llms-full.txt)",
              "- [Source code](https://github.com/DRACULA1729/tantu-lang)", ""]

    full = ["# Tantu", "", LLM_SUMMARY]
    for title, path in LLM_PAGES:
        md = (DOCS / f"{path}.md").read_text()
        md = re.sub(r"\A---\n.*?\n---\n", "", md, flags=re.S)  # drop the home page's hero frontmatter
        md = re.sub(r"<!--@include: \./(\S+?)-->",
                    lambda m: (DOCS / path).parent.joinpath(m[1]).read_text(), md)
        full += ["", "---", f"<!-- {SITE}/{path.removesuffix('index')} -->", "", md.strip()]
    return "\n".join(index), "\n".join(full) + "\n"


def main() -> None:
    (DOCS / ".vitepress").mkdir(parents=True, exist_ok=True)
    (DOCS / "reference").mkdir(parents=True, exist_ok=True)

    (DOCS / ".vitepress" / "tantu.tmLanguage.json").write_text(
        json.dumps(gen_grammar(), indent=2) + "\n")
    (DOCS / "reference" / "_errors.generated.md").write_text(gen_errors())
    (DOCS / "reference" / "_builtins.generated.md").write_text(gen_builtins())
    llms, llms_full = gen_llms()  # after the partials: the reference pages include them
    (DOCS / "public" / "llms.txt").write_text(llms)
    (DOCS / "public" / "llms-full.txt").write_text(llms_full)
    print("[build-docs-assets] wrote grammar + error/builtin reference partials + llms.txt")


if __name__ == "__main__":
    main()
